def tier_of(char):
    """字 → (系, 档位);不在补充池返回 None。"""
    return FILLER.get(char)


def score_of(tier):
    """档位 → (分数, 稀有度)。"""
    return TIERS[tier]


def split_useful(parts):
    """拆解产出 → (五行部件, 废料声旁)。废料合不出东西,是拆解的沉没成本。"""
    useful = [p for p in parts if attr_of(p)]
    return useful, [p for p in parts if not attr_of(p)]


def validate(chars, existing, index):
    """校验补充池:必须是 GB 常用字、有五行部件、且不在枢纽字体系那 146 字里。

    返回 {字: 问题描述},空表示全过。
    """
    problems = {}
    for char in chars:
        parts = decompose(char, index)
        if char in existing:
            problems[char] = "已在枢纽字体系表里"
        elif not is_displayable(char):
            problems[char] = "不在 CJK 基本区"
        elif gb_level(char) == 0:
            problems[char] = "不在 GB2312"
        elif not split_useful(parts)[0]:
            problems[char] = "拆不出五行部件"
        elif not split_useful(parts)[1]:
            problems[char] = "纯元素可达(该进枢纽字体系表)"
    return problems


# ---- 报表 ----

_HEAD = ("| 字 | 拼音 | 释义 | 拆解 | 拆出元素 | 废料 | 分数 | **稀有度** | 判定 | 选用 |\n"
         "|---|---|---|---|---|---|---|---|---|---|")


def _row(rec):
    score, rarity = score_of(rec["tier"])
    note = FILLER_NOTE.get(rec["char"], "")
    return (f"| {rec['char']} | {rec['pinyin']} | {rec['gloss']} | {' + '.join(rec['parts'])} "
            f"| {rec['useful']} | {rec['waste'] or '—'} | {score} | **{rarity}** "
            f"| {rec['tier']}{f'({note})' if note else ''} | |")


def build_report(by_attr, today, problems):
    total = sum(len(v) for v in by_attr.values())
    counts = {t: sum(1 for recs in by_attr.values() for r in recs if r["tier"] == t)
              for t in TIERS}
    out = [f"""# 补充字池(白绿卡来源)

> 生成:{today},`tools/pipeline/report_filler_chars.py`
> 从 GB2312 常用字里挑的 **{total}** 个字,全部满足:含五行部件、**不可由元素合成**、
> 不在 `字卡稀有度与入选建议.md` 那 146 字里。⚠️ 编辑本表请保存为 UTF-8。

## 这批字解决什么问题

枢纽字体系那 146 字全是**纯元素可达**的——能合成,所以贵,分数集中在紫蓝两档,
撑不起白绿。本表的字含一个非五行声旁(烧 = 火 + 尧),**合不出来,只能拆**:

- 拆出的五行部件入池(烧 → 火),声旁是废料(尧 合不出任何东西)
- 这正是 D5 的设计:每回合送 1 张随机字,元素的唯一来源是拆字
- 也正是 3.6「拆 vs 留」的日常——一张 **烧** 打出去是伤害,拆开是一个火

所以它们是**基础卡**:白绿档为主,靠字义威力感往上够到蓝紫,**紫色封顶**——
能合成的字(炎/焱/燚)才配拿橙红,合不出来的字不该压过它们。

## 评分只有一维

字义贴合六系特性的程度,四档:

| 档位 | 分数 | 稀有度 | 含义 | 本表字数 |
|---|---|---|---|---|
""" + "\n".join(f"| **{t}** | {TIERS[t][0]} | {TIERS[t][1]} | {desc} | {counts[t]} |"
                for t, desc in [("核心", "字义就是这个机制本身(烧 / 垒 / 慑)"),
                                ("贴合", "明确指向该机制(熔 / 碉 / 惶)"),
                                ("相关", "属性对但不是机制(炉 / 坡 / 懒)"),
                                ("沾边", "只是这一系的物件(灯 / 尘 / 念)")]) + """

成本、跨系、相生、横向那四维在这里都不适用:这些字合不出来,也当不了部件。

## 六系特性(判定依据)

| 系 | 特性 |
|---|---|
""" + "\n".join(f"| {a} | {t[0]} —— {t[1]} |" for a, t in S.ELEMENT_TRAITS.items()) + "\n"]

    if problems:
        out.append("\n> ⚠️ 以下字没通过校验,已从表中剔除:"
                   + "、".join(f"{c}({why})" for c, why in problems.items()) + "\n")

    for i, attr in enumerate("火木水金土心"):
        recs = by_attr.get(attr, [])
        out.append(f"\n## {'一二三四五六'[i]} · {attr}系({len(recs)} 个)"
                   f"—— {S.ELEMENT_TRAITS[attr][0]}\n")
        order = {t: i for i, t in enumerate(TIERS)}
        out.append("\n".join([_HEAD] + [_row(r) for r in sorted(
            recs, key=lambda r: (order[r["tier"]], r["char"]))]))
    out.append("")
    return "\n".join(out)


def main():
    sys.setrecursionlimit(10000)
    entries = parse_ids_text((ROOT / "data/raw/ids.txt").read_text(encoding="utf-8"))
    index = build_index(entries)
    readings = readings_map(json.load(open(ROOT / "data/raw/xinhua_word.json")))
    existing = {r["char"] for recs in S.build_records().values() for r in recs}

    problems = validate(FILLER, existing, index)
    by_attr = defaultdict(list)
    for char, (attr, tier) in FILLER.items():
        if char in problems:
            continue
        parts = decompose(char, index)
        useful, waste = split_useful(parts)
        pinyin, gloss = readings.get(char, ("—", ""))
        by_attr[attr].append({"char": char, "tier": tier, "parts": parts,
                              "useful": " ".join(useful), "waste": " ".join(waste),
                              "pinyin": pinyin, "gloss": gloss})

    text = build_report(by_attr, datetime.date.today().isoformat(), problems)
    path = ROOT.parent.parent / "docs/design/字选型/补充字池(白绿卡).md"
    path.write_text(text)
    print("写入", path.name,
          f"({sum(len(v) for v in by_attr.values())} 字通过,{len(problems)} 字被剔除)")
    for char, why in problems.items():
        print("  剔除", char, why)


if __name__ == "__main__":
    main()
