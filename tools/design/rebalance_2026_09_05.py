import re
def dot_equiv(n): return n*(n+1)//2*20
def parse_burn(t):
    m=re.fullmatch(r'(全体)?灼烧(\d+)',t)
    return (int(m.group(2)),bool(m.group(1))) if m else None

rows,problems=[],[]
for c in R:
    ra,el,form,k=c['ra'],c['el'],c['form'],K[c['ra']]
    A=dict(zip('单攻 全体 护盾 治疗 召数 召血 召攻 流血 护甲'.split(),ANCHOR[ra]))
    ts=[t for t in c['traits'] if t not in FORM_MOD]
    # 系印记(2026-09-07 改为**按规则**判定):免配额免计价,但**要留在表上**。
    #
    # 两处此前的毛病,一起修:
    # ① 印记被 remove 之后就从「特性技能」列里消失了 —— 而 §6 是 P2 落地的施工图,
    #    表上没写就落不了地(P2 Task 4a 正因此漏掉土系召唤字的入场护盾);
    # ② 印记原先靠 roster 逐字写对,于是漏了一片 —— 金系 9 个攻击字(利/锋/锥/剑/剿/
    #    铡/剁/鍂/刲)一个都没写「叠战意」,`桂` 也漏了「入场护盾」。而用户的要求是
    #    「金系**每张**攻击字自带战意」,那是规则不是逐字配置(本节标题就叫「规则的产物」)。
    #
    # 所以改成按形态判定:金系 atk 一律带战意印,土系 sum 一律带入场护盾印。
    # roster 里显式写了的照旧摘掉,避免重复计价。
    mark=MARK_TRAIT.get(el)
    marked=bool(mark) and ((el=='金' and form=='atk') or (el=='土' and form=='sum'))
    if mark and mark in ts: ts.remove(mark)
    # 水系印记(免配额但照常计价,见 MARK_FREE_QUOTA_ONLY 定义处)——只在数配额时摘掉,
    # 定价那一段仍用完整的 ts,一条都不能少。
    ts_quota=[t for t in ts if t not in MARK_FREE_QUOTA_ONLY]
    lo,hi=QUOTA[ra]
    if not (lo<=len(ts_quota)<=hi): problems.append(f"{c['id']}({ra}) {len(ts_quota)} 条 vs 配额 {lo}~{hi}:{ts_quota}")

    ratio,dot_abs,burn='' ,0,''
    ratio=0.0
    ratio_free=0.0   # MARK_FREE_QUOTA_ONLY 那几条对偶增益贡献的预算 —— 只用来豁免 0.60 上限检查,
                      # 不影响 ratio 本身(atk/护盾/治疗依旧照实吃这部分预算,§三 要求「照常计价」)
    for t in ts:
        b=parse_burn(t)
        if b:
            n,all_=b
            dot_abs+=int(round((dot_equiv(n)-dot_equiv(1))*k))   # 印记免第 1 层;DOT 同样吃档位系数
            burn=f"{'全体' if all_ else ''}灼烧 {n}"
            continue
        if t not in PRICE: problems.append(f"{c['id']}: {t} 没有定价"); continue
        p=PRICE[t]*k
        ratio+=p
        if t in MARK_FREE_QUOTA_ONLY: ratio_free+=p
    if el=='木' and form=='sum' and ts:
        ratio-=PRICE.get(ts[0],0)*k   # 木系印记:第 1 条被动免计价(但占配额)
    if not burn:
        for t in c['traits']:
            b=parse_burn(t)
            if b: burn=f"{'全体' if b[1] else ''}灼烧 {b[0]}"

    def bud(base): return max(0,int(round(base*(1-ratio)))-dot_abs)
    atk=sh=hl=sm=ar=ul=''
    # 召唤护盾点数(§10.1 + §10.3)与金系战意层数(§10.1)—— 都是印记落地要产出的数值。
    ss=mo=0
    # 金系印记的战意层数 = 免费 1 层(印记)+ 价目表买来的层数(战意+2 / 战意+3)。
    # ⚠ 这一列**不吃 ratio** —— 印记免计价,买来的那几层已经在 ratio 里付过钱了。
    mo=(MARK_MORALE if marked and el=='金' else 0)+sum(int(t[3:]) for t in ts if t.startswith('战意+'))
    if form=='atk': atk=bud(A['单攻'])
    elif form=='aoe': atk=bud(A['全体'])
    elif form=='sum':
        r=c['tank']/100.0
        keep = 0.0 if c['tank']==100 else ratio      # 纯肉盾:被动免计价
        n=c['count']
        # 总量守恒:锚点是「只数 × 单只」的总预算,只数改了就把总量摊到新的只数上
        hp_tot=A['召数']*A['召血']; at_tot=A['召数']*A['召攻']
        hp=int(round((hp_tot/n+at_tot/n*ATK_TO_HP*r)*(1-keep)))
        at=int(round(at_tot/n*(1-r)*SUM_ATK_F*(1-keep)))
        # 召唤护盾(2026-09-08,§10.2 订正):「入场护盾」(土系印记)与「光环盾」是**同一个
        # 机制** —— 两者都只能落到 EffectDef.SummonShield 这一个字段上,而一个 Summon 效果
        # 只有一个该字段,不可能同时存在两份,必须**合并成一个数值**。
        # 它给召唤物护盾的同时让玩家攒厚(BattleEngine 那行 GainHeft(shieldGrant)),
        # 是土系召唤字唯一能攒厚的路径。
        # ⚠ 顺序是硬的:盾量依赖血量、血量依赖 ratio、ratio 依赖光环盾**价格**(常量)——
        # 先定价 → 出血攻 → 再按血量算盾量,反过来算不出。
        ss=(MARK_SHIELD if marked else 0)
        if '光环盾' in ts: ss+=int(round(hp*AURA_SHIELD_F/10.0))*10
        sm=f"{n} 只 · {hp} 血 / {at} 攻"+(f" · 盾 {ss}" if ss else "")
    elif form=='dual_s':
        g=GROUP_F if '群盾' in c['traits'] else 1.0
        atk=bud(A['全体'] if g<1 else A['单攻'])
        sh=int(round(A['护盾']*SHIELD_F*g*(1-ratio)))
    elif form=='dual_h':
        g=GROUP_F if '群疗' in c['traits'] else 1.0
        atk=bud(A['全体'] if g<1 else A['单攻'])
        hl=int(round(A['治疗']*HEAL_F*g*(1-ratio)))
        if '持续治疗' in c['traits']: hl=f"{hl//3}×3"
    # 召唤被动版护甲与玩家侧同取档位锚点(塔 = 紫档 7):落地是挂进召唤物自己的状态袋,
    # 数值口径不该因为「护的是谁」而分叉。
    if '护甲' in ts or '护甲(召)' in ts: ar=A['护甲']
    if '流血' in ts: pass
    if '终极技' in ts: ul=A['全体']//5
    rows.append(dict(**c,atk=atk,sh=sh,hl=hl,sm=sm,ar=ar,ul=ul,burn=burn,ratio=ratio,dot=dot_abs,ts=ts,
                     ss=ss,mo=mo,mark=mark if marked else '',ratio_free=ratio_free))

# 档位单调性:同系同形态,高档不得低于低档
def total(r):
    v=r['atk'] if isinstance(r['atk'],int) else 0
    for t in r['traits']:
        b=parse_burn(t)
        if b: v+=dot_equiv(b[0])
    if isinstance(r['ul'],int): v+=r['ul']*10        # 终极技满 10 层
    if isinstance(r['sm'],str) and r['sm']:
        # 召唤当量沿用 tools/balance 的 Power() 口径:(血 + 攻×3) × 只数 ÷ 2。
        # 只按攻击算会把肉盾字判成倒挂(桂 3×30 攻 < 林 2×53 攻,而 桂 血量是 林 的 1.9 倍)。
        import re as _r; m=_r.findall(r'(\d+)',r['sm'])
        v+=(int(m[1])+int(m[2])*3)*int(m[0])//2
    return v
def mono(col,label,fn=None):
    bad=[]
    for el in '金木水火土':
        pass
    for el,fm in [(e,f) for e in '金木水火土' for f in ('atk','aoe','sum','dual_s','dual_h')]:
        best={}
        for r in [x for x in rows if x['el']==el and x['form']==fm
                  and '终极技' not in x['traits']
                  and not ({'群疗','群盾'} & set(x['traits']))
                  # 2026-09-16:携带「对偶印记」(§三 MARK_FREE_QUOTA_ONLY)的卡不参与本比较 ——
                  # 理由同「终极技/群疗/群盾」的既有豁免:它们的价值有一大块压在对偶增益
                  # 本身上,total()/hl/sh 这几列只量攻击面或护盾面的数字,量不到那部分,
                  # 用这几列去跟没有对偶增益的低档卡比高低不是同一个维度的比较。
                  and not x['ratio_free']
                  # 纯 DOT 单特性的 atk/aoe 卡同理排除:dot_equiv 的「首层免费」折扣与 bud()
                  # 的预算扣减在 k=1(白/绿档)时恰好互相抵消,total() 对这类卡是个与层数无关
                  # 的常数,跟层数、跟其它卡比较都没有意义(2026-09-16,爆 蓝→绿 暴露的既有
                  # 计分公式盲区,不是本次改动引入的新数值问题)。
                  and not (x['form'] in ('atk','aoe') and x['ts'] and all(parse_burn(t) for t in x['ts']))]:
            v=fn(r) if fn else (r[col] if isinstance(r[col],int) else None)
            if not v: continue
            best.setdefault(ORDER.index(r['ra']),[]).append((r['id'],v))
        tiers=sorted(best)
        for a,b in zip(tiers,tiers[1:]):
            hi_a=max(v for _,v in best[a]); lo_b=min(v for _,v in best[b])
            if lo_b<hi_a:
                nb=[i for i,v in best[b] if v==lo_b][0]; na=[i for i,v in best[a] if v==hi_a][0]
                bad.append(f"{el}系·{fm} {label}:{ORDER[b]}档 {nb} {lo_b} < {ORDER[a]}档 {na} {hi_a}")
    return bad
