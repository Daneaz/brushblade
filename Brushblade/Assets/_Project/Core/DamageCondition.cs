namespace Brushblade.Core
{
    /// <summary>伤害的**条件加成**:目标带某个状态时,这一记的基础值翻倍(2026-08-25)。
    ///
    /// 它把原先写死的 <c>DoubleVsBurning</c> 布尔位泛化开 —— 那条 2026-08-12 上线时只服务
    /// 灼 一个字,而「低档铺状态、高档收割」这条设计语言(spec §11)需要每一系都有一对:
    ///
    /// | 系 | 低档铺状态 | 高档收割 |
    /// |---|---|---|
    /// | 火 | 灼 / 热 / 烧 / 焦 / 爆 上灼烧 | 灼(自消费)、炸(引爆) |
    /// | 土 | 碎 / 溃 破甲 | 垚 对破甲目标双倍 |
    /// | 水 | 冻 / 藤 冻结、冷 / 蕉 减速 | 冰 对受控目标双倍 |
    /// | 金 | 劈 流血 | 铡 对流血目标双倍 |
    ///
    /// **只作用于基础值,在生克之前**(见 BattleEngine.BaseValue)—— 翻倍与相生 ×3 相乘,
    /// 不是相加。改这个顺序会让「灼打相生目标」的量整个变一档。
    /// </summary>
    public enum DamageCondition
    {
        /// <summary>无条件(缺省)。</summary>
        None = 0,

        /// <summary>目标带灼烧(灼,10.3.1)。</summary>
        Burning = 1,

        /// <summary>目标流血(2026-08-25,铡)。流血是无属性 DOT,与灼烧互不影响。</summary>
        Bleeding = 2,

        /// <summary>目标**行动受阻** —— 冻结或被减速(2026-08-25,冰)。
        /// 两个状态合成一条而不是拆成两个:玩家读到的是「打不动的目标吃双倍」,
        /// 拆开会逼着卡面写「对冻结或减速目标」,而这两者在玩法上本来就是一路。</summary>
        Controlled = 3,

        /// <summary>目标已被破甲(2026-08-25,垚)。看的是**状态在不在**,不看削了多少点 ——
        /// 按点数分档会让「削 10 的 溃」和「削 20 的 碎」触发出不同结果,那是第二条隐藏规则。</summary>
        ArmorBroken = 4,
    }
}
